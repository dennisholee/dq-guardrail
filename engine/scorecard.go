package engine

import (
	"bytes"
	"fmt"
	"sort"
	"strings"
)

// GenerateScorecard renders the readiness view from the artefacts themselves. It exists because
// the previous scorecard was hand-maintained and went stale every time a rule or a fixture
// changed — the same defect the generated rule index exists to prevent, applied to the document
// that describes coverage.
func GenerateScorecard(m *Model) ([]byte, error) {
	var b bytes.Buffer

	b.WriteString("# Party model — readiness scorecard\n\n")
	b.WriteString("Generated by `dqctl scorecard` from the artefacts in this tree. **Do not edit**: run\n")
	b.WriteString("`dqctl scorecard --root examples/party-model` to refresh it, and `--check` in CI to\n")
	b.WriteString("guarantee it is current.\n\n")
	b.WriteString("It reports what the repository *declares* against what it *enforces*. It is not a\n")
	b.WriteString("measurement of production data, and it is not a statement that any threshold is met.\n\n")

	// Inventory.
	objectRules, intentRules := 0, 0
	tierCount := map[int]int{}
	dimensionCount := map[string]int{}
	severityCount := map[string]int{}
	for _, p := range m.AllPacks() {
		for _, r := range p.Rules() {
			if p.IsIntent() {
				intentRules++
			} else {
				objectRules++
			}
			if prefix := strings.SplitN(r.ID, "-", 2)[0]; prefix == "SYN" {
				tierCount[0]++
			} else if prefix == "SEM" {
				tierCount[1]++
			} else if prefix == "STA" {
				tierCount[2]++
			}
			dimensionCount[r.Dimension]++
			severityCount[r.Severity]++
		}
	}

	fixtures := 0
	for _, p := range m.AllPacks() {
		fixtures += len(p.Spec.Tests)
	}

	b.WriteString("## Inventory\n\n| Item | Count |\n|---|---|\n")
	fmt.Fprintf(&b, "| Documents | %d |\n", len(m.Docs))
	fmt.Fprintf(&b, "| Canonical contracts | %d |\n", len(m.Contracts))
	fmt.Fprintf(&b, "| Value sets | %d |\n", len(m.ValueSets))
	fmt.Fprintf(&b, "| Object rules | %d |\n", objectRules)
	fmt.Fprintf(&b, "| Intent rules | %d |\n", intentRules)
	fmt.Fprintf(&b, "| Fixtures | %d |\n", fixtures)
	fmt.Fprintf(&b, "| Compiled plans | %d |\n", len(m.Plans))
	fmt.Fprintf(&b, "| Committed verdicts | %d |\n\n", len(m.Verdicts))

	// Coverage: the promise-versus-check table.
	b.WriteString("## Thresholds declared vs dimensions enforced\n\n")
	b.WriteString("A threshold in `meta.yaml` is a target. A rule pack is what is checked. The gap between\n")
	b.WriteString("them is a promise nobody is keeping yet.\n\n")
	b.WriteString("| Object | Declared | Covered | Gap |\n|---|---|---|---|\n")
	gaps := 0
	for _, c := range CoverageReport(m) {
		gap := "none"
		if len(c.Gaps) > 0 {
			gap = "**" + strings.Join(c.Gaps, "**, **") + "**"
			gaps += len(c.Gaps)
		}
		fmt.Fprintf(&b, "| `%s` | %d | %d | %s |\n", c.Object, len(c.Declared), len(c.Covered), gap)
	}
	fmt.Fprintf(&b, "\n%d declared dimension(s) have no rule covering them.\n\n", gaps)

	// Rules by dimension.
	b.WriteString("## Rules by dimension\n\n| Dimension | Rules |\n|---|---|\n")
	dims := make([]string, 0, len(dimensionCount))
	for dim := range dimensionCount {
		dims = append(dims, dim)
	}
	sort.Strings(dims)
	for _, dim := range dims {
		fmt.Fprintf(&b, "| %s | %d |\n", dim, dimensionCount[dim])
	}
	fmt.Fprintf(&b, "\nBy tier: %d structural, %d semantic, %d stateful.\n\n", tierCount[0], tierCount[1], tierCount[2])

	b.WriteString("## Rules by severity\n\n")
	b.WriteString("Severity drives what a channel does with a violation, so the distribution matters more\n")
	b.WriteString("than the total.\n\n")
	b.WriteString("| Severity | Rules |\n|---|---|\n")
	for _, sev := range []string{SeverityViolationCritical, SeverityViolationMajor, SeverityViolationMinor} {
		fmt.Fprintf(&b, "| %s | %d |\n", sev, severityCount[sev])
	}
	b.WriteString("\n")

	if err := writeWaivers(&b, m); err != nil {
		return nil, err
	}
	writeFixtureCoverage(&b, m)

	return b.Bytes(), nil
}

func writeWaivers(b *bytes.Buffer, m *Model) error {
	type waiver struct{ kind, rule, expires, approved string }
	rows := []waiver{}

	for _, p := range m.AllPacks() {
		for _, rx := range p.Spec.Relax {
			rows = append(rows, waiver{
				kind:     "relax (" + p.Metadata.Name + ")",
				rule:     rx.Rule,
				expires:  rx.ExpiresAt,
				approved: strings.Join(rx.ApprovedBy, ", "),
			})
		}
	}
	for _, bd := range m.Bindings {
		for _, s := range bd.Spec.Suppress {
			rows = append(rows, waiver{
				kind:     "suppress (" + bd.Metadata.Name + ")",
				rule:     s.Rule,
				expires:  s.Until,
				approved: s.Approver,
			})
		}
	}

	b.WriteString("## Waivers\n\n")
	if len(rows) == 0 {
		b.WriteString("None. No rule is currently waived by intent or suppressed by a binding.\n\n")
		return nil
	}
	sort.Slice(rows, func(i, j int) bool { return rows[i].rule < rows[j].rule })
	b.WriteString("| Kind | Rule | Expires | Approved by |\n|---|---|---|---|\n")
	for _, r := range rows {
		fmt.Fprintf(b, "| %s | `%s` | %s | %s |\n", r.kind, r.rule, r.expires, r.approved)
	}
	b.WriteString("\nEvery waiver expires and names its approvers. A waiver with neither is a permanent\npolicy change that avoided review.\n\n")
	return nil
}

func writeFixtureCoverage(b *bytes.Buffer, m *Model) {
	b.WriteString("## Fixtures per rule\n\n| Pack | Rule | pass | fail | edge |\n|---|---|---|---|---|\n")
	rows := 0
	for _, p := range m.AllPacks() {
		counts := map[string]int{}
		for _, t := range p.Spec.Tests {
			counts[t.Rule+"/"+t.Expect]++
		}
		for _, r := range p.Rules() {
			fmt.Fprintf(b, "| %s | `%s` | %d | %d | %d |\n",
				p.Metadata.Name, r.ID,
				counts[r.ID+"/pass"], counts[r.ID+"/fail"], counts[r.ID+"/edge"])
			rows++
		}
	}
	if rows == 0 {
		b.WriteString("\nNo rules are declared.\n\n")
		return
	}
	b.WriteString("\nA rule with no failing fixture is a rule nobody has proven can fail. Rules whose\n")
	b.WriteString("assertion reads the clock cannot have a deterministic fixture, and the validator lets\n")
	b.WriteString("them omit one.\n")
}
