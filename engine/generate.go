package engine

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"sort"

	"gopkg.in/yaml.v3"
)

// RuleIndexPath is the derived artefact: which rules will run on each endpoint.
//
// It is a sidecar rather than an embedded `x-dq-rules` on each operation, and that is a
// deliberate deviation from the design's one-line description. Writing into the OpenAPI
// document requires a round-trip through a YAML emitter, and the emitter available here
// collapses folded block scalars and reindents the whole file — a 121-line diff on a
// hand-authored contract, repeated on every hand edit. A generated sidecar keeps review
// diffs honest; embedding becomes worthwhile only behind a formatting-preserving writer.
const RuleIndexPath = "spec/openapi/generated/x-dq-rules.yaml"

// GeneratedPath is the rule index for one endpoint.
type GeneratedPath struct {
	Intent        string   `yaml:"intent"`
	Object        string   `yaml:"object"`
	ObjectVersion string   `yaml:"objectVersion"`
	Plan          string   `yaml:"plan"`
	PlanDigest    string   `yaml:"planDigest"`
	Rules         []string `yaml:"rules"`
}

// GeneratedRuleIndex is the whole artefact.
type GeneratedRuleIndex struct {
	Generated struct {
		By   string `yaml:"by"`
		From string `yaml:"from"`
	} `yaml:"generated"`
	Paths map[string]GeneratedPath `yaml:"paths"`
}

// addressKeyOf builds the endpoint an HTTP plan answers on.
func addressKeyOf(p *Plan) string { return "/" + p.Intent + "-" + p.Object }

// GenerateRuleIndex derives the artefact from the compiled plans. Nothing here is read from
// the artefact itself, so a stale copy cannot influence its own regeneration.
func GenerateRuleIndex(m *Model) ([]byte, error) {
	idx := GeneratedRuleIndex{}
	idx.Generated.By = "dqctl generate"
	idx.Generated.From = "evidence/plans"
	idx.Paths = map[string]GeneratedPath{}

	paths := make([]string, 0, len(m.Plans))
	for p := range m.Plans {
		paths = append(paths, p)
	}
	sort.Strings(paths)

	for _, key := range paths {
		plan := m.Plans[key]
		if plan.Channel != "http" {
			continue
		}
		rules := make([]string, 0, len(plan.Rules))
		for _, r := range plan.Rules {
			rules = append(rules, r.ID)
		}
		idx.Paths[addressKeyOf(plan)] = GeneratedPath{
			Intent:        plan.Intent,
			Object:        plan.Object,
			ObjectVersion: plan.ObjectVersion,
			Plan:          "plans/" + filepath.Base(plan.Path),
			PlanDigest:    plan.Digest,
			Rules:         rules,
		}
	}

	var buf bytes.Buffer
	buf.WriteString("# Generated by dqctl generate. Do not edit.\n")
	buf.WriteString("# Source: the compiled plans under evidence/plans. `dqctl generate --check` fails\n")
	buf.WriteString("# when this file and the plans disagree.\n")

	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(idx); err != nil {
		return nil, err
	}
	if err := enc.Close(); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// CheckRuleIndex compares the committed artefact with a freshly derived one, reporting each
// endpoint that disagrees rather than a single "stale" verdict.
func CheckRuleIndex(m *Model, committed []byte) ([]string, error) {
	fresh, err := GenerateRuleIndex(m)
	if err != nil {
		return nil, err
	}
	if bytes.Equal(fresh, committed) {
		return nil, nil
	}

	var want, got GeneratedRuleIndex
	if err := yaml.Unmarshal(fresh, &want); err != nil {
		return nil, err
	}
	if err := yaml.Unmarshal(committed, &got); err != nil {
		return []string{"the committed rule index does not parse: " + err.Error()}, nil
	}

	problems := []string{}
	keys := map[string]bool{}
	for k := range want.Paths {
		keys[k] = true
	}
	for k := range got.Paths {
		keys[k] = true
	}
	sorted := make([]string, 0, len(keys))
	for k := range keys {
		sorted = append(sorted, k)
	}
	sort.Strings(sorted)

	for _, k := range sorted {
		w, inWant := want.Paths[k]
		g, inGot := got.Paths[k]
		switch {
		case !inGot:
			problems = append(problems, fmt.Sprintf("%s is missing from the rule index", k))
		case !inWant:
			problems = append(problems, fmt.Sprintf("%s is in the rule index but answers no plan", k))
		case w.PlanDigest != g.PlanDigest:
			// The rule IDs can stay the same while the rules themselves change, so the index
			// pins the plan it was derived from rather than trusting the ID list.
			problems = append(problems, fmt.Sprintf("%s was derived from a different plan", k))
		case len(w.Rules) != len(g.Rules) || !sameSet(w.Rules, g.Rules):
			problems = append(problems, fmt.Sprintf("%s runs %d rules, the index says %d", k, len(w.Rules), len(g.Rules)))
		}
	}
	if len(problems) == 0 {
		problems = append(problems, "the rule index differs from the plans (formatting or header)")
	}
	return problems, nil
}

// WriteRuleIndex writes the artefact under root.
func WriteRuleIndex(root string, data []byte) (string, error) {
	path := filepath.Join(root, filepath.FromSlash(RuleIndexPath))
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return "", err
	}
	return path, os.WriteFile(path, data, 0o644)
}

// ReadRuleIndex reads the committed artefact, if present.
func ReadRuleIndex(root string) ([]byte, error) {
	return os.ReadFile(filepath.Join(root, filepath.FromSlash(RuleIndexPath)))
}
