package engine

import (
	"bytes"
	"fmt"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"
)

// BuiltFrom records the provenance stamped into a manifest.
type BuiltFrom struct {
	Commit string
	Ref    string
	Epoch  int64
	Dqctl  string
}

// BuildManifest derives the bundle manifest from the tree. Nothing is taken on trust: every
// digest comes from the file being described, so a manifest cannot claim a state the tree is
// not in.
func BuildManifest(m *Model, from BuiltFrom) (*Bundle, error) {
	b := &Bundle{BundleFormat: 2}
	b.BuiltFrom.Commit = from.Commit
	b.BuiltFrom.Ref = from.Ref
	b.BuiltFrom.Epoch = from.Epoch
	b.BuiltFrom.Dqctl = from.Dqctl

	for _, name := range sortedContractNames(m) {
		c := m.Contracts[name]
		digest, err := m.DigestFile(c.Path)
		if err != nil {
			return nil, err
		}
		obj := BundleObject{Name: name, Version: c.Version, ContractDigest: digest}
		if meta := m.Metas[name]; meta != nil {
			obj.Criticality = meta.Criticality
			obj.Sensitivity = meta.Sensitivity
		}
		b.Objects = append(b.Objects, obj)
	}

	// Value sets and the intent registry are carried by the bundle, so they are described by it.
	// Until 1.3.0 they were not, and a consumer had no per-artefact claim about the enumerations
	// the rules are written against.
	names := make([]string, 0, len(m.ValueSets))
	for name := range m.ValueSets {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		vs := m.ValueSets[name]
		digest, err := m.DigestFile(vs.Path)
		if err != nil {
			return nil, err
		}
		b.ValueSets = append(b.ValueSets, BundleValueSet{
			Name:    name,
			Version: vs.Version,
			Path:    vs.Path,
			Digest:  digest,
		})
	}
	if m.Registry != nil {
		digest, err := m.DigestFile(m.Registry.Path)
		if err != nil {
			return nil, err
		}
		b.Intents = &BundleIntents{Path: m.Registry.Path, Digest: digest}
	}

	packs := m.AllPacks()
	sort.Slice(packs, func(i, j int) bool { return packs[i].Metadata.Name < packs[j].Metadata.Name })
	providers := map[string]bool{}
	for _, p := range packs {
		count := len(p.Rules())
		b.Packs = append(b.Packs, BundlePack{
			Name:      p.Metadata.Name,
			Version:   p.Metadata.Version,
			Digest:    p.Digest,
			RuleCount: &count,
		})
		for _, rx := range p.Spec.Relax {
			// The manifest records who approved a waiver and until when; the justification
			// stays in the pack, where the author wrote it. BundleRelax has no field for it.
			b.Relax = append(b.Relax, BundleRelax{
				Rule:       rx.Rule,
				Layer:      rx.Layer,
				ApprovedBy: rx.ApprovedBy,
				ExpiresAt:  rx.ExpiresAt,
			})
		}
		for _, r := range p.Rules() {
			for _, need := range r.Needs {
				providers[need] = true
			}
		}
	}

	paths := make([]string, 0, len(m.Plans))
	for p := range m.Plans {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	for _, p := range paths {
		plan := m.Plans[p]
		b.Plans = append(b.Plans, BundlePlan{
			Plan:          strings.TrimPrefix(p, "evidence/"),
			Channel:       plan.Channel,
			Intent:        plan.Intent,
			Object:        plan.Object,
			ObjectVersion: plan.ObjectVersion,
			Digest:        plan.Digest,
		})
		for _, prov := range plan.Providers {
			providers[prov] = true
		}
	}

	b.Providers = make([]string, 0, len(providers))
	for p := range providers {
		b.Providers = append(b.Providers, p)
	}
	sort.Strings(b.Providers)
	return b, nil
}

// MarshalManifest renders a manifest as YAML with a header explaining what it is.
func MarshalManifest(b *Bundle) ([]byte, error) {
	body, err := yaml.Marshal(b)
	if err != nil {
		return nil, err
	}
	header := "# Generated by dqctl bundle. Do not edit: every digest below is computed\n" +
		"# from the file it describes, and `dqctl bundle --check` fails when they disagree.\n"
	return append([]byte(header), body...), nil
}

// ManifestBytes re-renders a parsed manifest so two manifests can be compared structurally.
func ManifestBytes(b *Bundle) ([]byte, error) { return yaml.Marshal(b) }

// DigestBytes is the digest a manifest would carry for a byte slice, e.g. the archive itself.
func DigestBytes(data []byte) string { return digestOf(data) }

// CompareManifests reports where two manifests disagree. Order is not significant: a
// manifest is a set of claims about files, not a sequence.
func CompareManifests(want, got *Bundle) []string {
	problems := []string{}

	if want.BundleFormat != got.BundleFormat {
		problems = append(problems, fmt.Sprintf("bundleFormat %d != %d", want.BundleFormat, got.BundleFormat))
	}

	wo, go_ := normaliseObjects(want.Objects), normaliseObjects(got.Objects)
	if !equalJSON(wo, go_) {
		problems = append(problems, "objects differ from the tree")
	}
	wp, gp := normalisePacks(want.Packs), normalisePacks(got.Packs)
	if !equalJSON(wp, gp) {
		problems = append(problems, "packs differ from the tree")
	}
	wpl, gpl := normalisePlans(want.Plans), normalisePlans(got.Plans)
	if !equalJSON(wpl, gpl) {
		problems = append(problems, "plans differ from the tree")
	}
	if !equalJSON(sortedCopy(want.Providers), sortedCopy(got.Providers)) {
		problems = append(problems, "providers differ from the tree")
	}
	if !equalJSON(normaliseRelax(want.Relax), normaliseRelax(got.Relax)) {
		problems = append(problems, "relax entries differ from the tree")
	}
	// Value sets and the intent registry are claims like any other: a stale digest here is as
	// wrong as a stale contract digest, and until these comparisons existed nothing checked them.
	if !equalJSON(normaliseValueSets(want.ValueSets), normaliseValueSets(got.ValueSets)) {
		problems = append(problems, "valueSets differ from the tree")
	}
	if !equalJSON(want.Intents, got.Intents) {
		problems = append(problems, "intents differ from the tree")
	}
	return problems
}

func normaliseObjects(in []BundleObject) []BundleObject {
	out := append([]BundleObject(nil), in...)
	sort.Slice(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	return out
}

func normalisePacks(in []BundlePack) []BundlePack {
	out := append([]BundlePack(nil), in...)
	sort.Slice(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	return out
}

func normalisePlans(in []BundlePlan) []BundlePlan {
	out := append([]BundlePlan(nil), in...)
	sort.Slice(out, func(i, j int) bool { return out[i].Plan < out[j].Plan })
	return out
}

func normaliseRelax(in []BundleRelax) []BundleRelax {
	out := append([]BundleRelax(nil), in...)
	sort.Slice(out, func(i, j int) bool { return out[i].Rule < out[j].Rule })
	return out
}

func normaliseValueSets(in []BundleValueSet) []BundleValueSet {
	out := append([]BundleValueSet(nil), in...)
	sort.Slice(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	return out
}

func sortedCopy(in []string) []string {
	out := append([]string(nil), in...)
	sort.Strings(out)
	return out
}

func equalJSON(a, b any) bool {
	ab, err1 := yaml.Marshal(a)
	bb, err2 := yaml.Marshal(b)
	return err1 == nil && err2 == nil && bytes.Equal(ab, bb)
}

func sortedContractNames(m *Model) []string {
	out := make([]string, 0, len(m.Contracts))
	for name := range m.Contracts {
		out = append(out, name)
	}
	sort.Strings(out)
	return out
}
