package engine

import (
	"fmt"

	"gopkg.in/yaml.v3"
)

// GenerateCRD renders a CustomResourceDefinition for QualityBinding from its JSON Schema.
func GenerateCRD(schemaDoc any) ([]byte, error) {
	root, ok := schemaDoc.(map[string]any)
	if !ok {
		return nil, fmt.Errorf("the binding schema is not a mapping")
	}
	props, ok := root["properties"].(map[string]any)
	if !ok {
		return nil, fmt.Errorf("the binding schema declares no properties")
	}

	apiVersion, ok := props["apiVersion"].(map[string]any)
	if !ok {
		return nil, fmt.Errorf("the binding schema declares no apiVersion")
	}
	group := "dq.example.com"
	if c, ok := apiVersion["const"].(string); ok && len(c) > 3 {
		group = c[:len(c)-len("/v1")]
	}

	spec, ok := props["spec"].(map[string]any)
	if !ok {
		return nil, fmt.Errorf("the binding schema declares no spec")
	}
	specSchema, err := structural(spec)
	if err != nil {
		return nil, fmt.Errorf("spec: %w", err)
	}
	specSchema["x-kubernetes-validations"] = bindingCELRules()

	// metadata is deliberately not projected. The API server injects uid, creationTimestamp and
	// resourceVersion there, and a restrictive schema would prune them; ObjectMeta already
	// enforces the name and namespace patterns this schema states.
	metadataSchema := map[string]any{"type": "object"}

	openAPIV3Schema := map[string]any{
		"type": "object",
		"properties": map[string]any{
			"apiVersion": map[string]any{"type": "string"},
			"kind":       map[string]any{"type": "string", "enum": []any{"QualityBinding"}},
			"metadata":   metadataSchema,
			"spec":       specSchema,
			"status": map[string]any{
				"type": "object",
				"properties": map[string]any{
					"bundleDigest": map[string]any{"type": "string"},
					"lastApplied":  map[string]any{"type": "string", "format": "date-time"},
					"conditions": map[string]any{
						"type": "array",
						"items": map[string]any{
							"type": "object",
							"properties": map[string]any{
								"type":               map[string]any{"type": "string"},
								"status":             map[string]any{"type": "string"},
								"reason":             map[string]any{"type": "string"},
								"message":            map[string]any{"type": "string"},
								"lastTransitionTime": map[string]any{"type": "string", "format": "date-time"},
							},
							"required": []any{"type", "status"},
						},
					},
				},
			},
		},
		"required": []any{"spec"},
	}

	crd := map[string]any{
		"apiVersion": "apiextensions.k8s.io/v1",
		"kind":       "CustomResourceDefinition",
		"metadata":   map[string]any{"name": "qualitybindings." + group},
		"spec": map[string]any{
			"group": group,
			"names": map[string]any{
				"kind":     "QualityBinding",
				"listKind": "QualityBindingList",
				"plural":   "qualitybindings",
				"singular": "qualitybinding",
			},
			"scope": "Namespaced",
			"versions": []any{
				map[string]any{
					"name":                     "v1",
					"served":                   true,
					"storage":                  true,
					"schema":                   map[string]any{"openAPIV3Schema": openAPIV3Schema},
					"subresources":             map[string]any{"status": map[string]any{}},
					"additionalPrinterColumns": printerColumns(),
				},
			},
		},
	}

	out, err := yaml.Marshal(crd)
	if err != nil {
		return nil, err
	}
	header := "# Generated by dqctl crd from catalog/schemas/quality-binding.schema.yaml.\n" +
		"# The CRD schema is an OpenAPI v3.0 structural subset, so the two conditional constraints\n" +
		"# in the source schema are carried as CEL rules rather than if/then.\n"
	return append([]byte(header), out...), nil
}

func printerColumns() []any {
	return []any{
		map[string]any{"name": "Mode", "type": "string", "jsonPath": ".spec.mode"},
		map[string]any{"name": "Bundle", "type": "string", "jsonPath": ".spec.bundle"},
		map[string]any{"name": "Age", "type": "date", "jsonPath": ".metadata.creationTimestamp"},
	}
}
